"""Build/sign the account test app with official SDK tools."""

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / "tools/android-sdk"
BUILD = ROOT / "client/build/preview"
FIELD = ROOT / "client/fieldtest/src"

# Every device-control endpoint. A read-only build must contain none of these strings; a field-test
# build must contain all of them. The build fails otherwise, so "this APK cannot send a control
# request" is a checked property of the artifact rather than a claim about the source.
CONTROL_ROUTES = (
    "order/tcpDevice/downRate/rateOrder",
    "order/tcpDevice/query/downRateResult",
    "order/tcpDevice/closeOrder",
    "order/tcpDevice/closeOrder/result/query",
    "order/consumeOrder/result/query",
    "/api/v1/dev/start",
    "/api/v1/dev/end",
)
FIELD_VERSION_NAME = "2.3.2"
FIELD_LABEL = "科信小助手"

# Classes that only exist in the field-test source root. The check uses their dex type descriptors,
# which appear only when the class is actually defined or referenced — not a bare name, because
# "WaterControl" is also a substring of the unrelated method DeviceProfile.readyForWaterControl.
FIELD_ONLY_CLASSES = ("Lio/qzxy/lite/preview/WaterActivity;", "Lio/qzxy/lite/preview/WaterControl;")


def run(args):
    subprocess.run([str(a) for a in args], check=True)


def dex_literals(paths):
    """Printable ASCII runs found in the dex files, which is enough to spot route strings."""
    found = set()
    for path in paths:
        found.update(re.findall(rb"[\x20-\x7e]{6,}", path.read_bytes()))
    return {item.decode("ascii") for item in found}


def check_route_boundary(dex_dir, field_water):
    literals = dex_literals(sorted(dex_dir.glob("*.dex")))
    hits = {route: sum(route in item for item in literals) for route in CONTROL_ROUTES}
    hits.update({name: sum(name in item for item in literals) for name in FIELD_ONLY_CLASSES})
    if field_water:
        missing = [key for key, count in hits.items() if count == 0]
        if missing:
            raise RuntimeError("Field-test build is missing: " + ", ".join(missing))
    else:
        present = [key for key, count in hits.items() if count > 0]
        if present:
            raise RuntimeError("Read-only build leaked control routes or field-test classes: " + ", ".join(present))
    return hits


def write_build_flags(field_water, device_tests):
    package = BUILD / "generated/io/qzxy/lite/preview"
    package.mkdir(parents=True, exist_ok=True)
    source = package / "BuildFlags.java"
    source.write_text(
        "package io.qzxy.lite.preview;\n\n"
        "/** Generated by scripts/build_preview.py. Do not edit. */\n"
        "final class BuildFlags {\n"
        "    /** Compile-time switch: javac removes every branch guarded by a false constant. */\n"
        "    static final boolean WATER_CONTROL = " + ("true" if field_water else "false") + ";\n"
        "    static final boolean DEVICE_TESTS = " + ("true" if device_tests else "false") + ";\n"
        "    private BuildFlags() { }\n"
        "}\n", encoding="utf-8")
    return source


def main():
    device_tests = "--device-tests" in sys.argv
    field_water = "--field-water" in sys.argv
    if "--skip-tests" not in sys.argv:
        run([sys.executable, ROOT / "scripts/test_core.py"])
    properties = subprocess.run(["java", "-XshowSettings:properties", "-version"], capture_output=True, text=True, errors="replace", check=True)
    found = re.search(r"java.home\s*=\s*(.+)", properties.stderr)
    if found is None:
        raise RuntimeError("JDK location not found")
    jdk = Path(os.environ.get("QZXY_JDK_HOME", found.group(1).strip()))
    tools = SDK / "build-tools/36.0.0"
    android = SDK / "platforms/android-36/android.jar"
    zxing = ROOT / "tools/zxing/core-3.5.3.jar"
    if not zxing.exists() or hashlib.sha256(zxing.read_bytes()).hexdigest() != "8d8064c1636fdaef7189dd9055c7d59950a8940a12f2293956446ec3c109fd82":
        raise RuntimeError("Download the pinned ZXing core dependency documented in client/THIRD_PARTY.md")
    # Alipay's official Android SDK, pinned by hash: the login page hands the reader to the Alipay
    # app, and only this SDK speaks its bound-service protocol. Its manifest, resource ids and
    # classes are merged below by hand because there is no Gradle here.
    alipay_aar = ROOT / "tools/alipay/alipaysdk-android-15.8.42.aar"
    if not alipay_aar.exists() or hashlib.sha256(alipay_aar.read_bytes()).hexdigest() != "a6c301708b59a3a7cda843cf02e7b3b0b44afd96819f0a18890322e9868abf28":
        raise RuntimeError("Download the pinned Alipay SDK documented in client/THIRD_PARTY.md")
    pdf_hashes = {'bcpkix-jdk15to18-1.72.jar': 'd9b97477b72499bcee02f5a906510810257ff36a94bf69fbca0b1e65e7ffdb6e', 'bcprov-jdk15to18-1.72.jar': 'ea66ea8a450810b2193e8bf9a7ad3e46307c9896224c0f407d1b7d96ba1221cc', 'bcutil-jdk15to18-1.72.jar': 'd92184bdeb3105a11ad9e36acbd66b5f8eed091b08b9c8f3e2549e42b7f131f1', 'classes.jar': '35f592ed840ec0903546b086e6181589796edcf0a142e2a5d5f3a3cf1e74739c', 'pdfbox-android-2.0.27.0.aar': '30277f879cfd571db2a137582c95516a0d4ea6778e945519bc58ca93d57d88c7'}
    pdf_dir = ROOT / "tools/pdfbox"
    for name, digest in pdf_hashes.items():
        if hashlib.sha256((pdf_dir / name).read_bytes()).hexdigest() != digest:
            raise RuntimeError("PDF dependency hash mismatch: " + name)
    pdf_jars = sorted(pdf_dir.glob("*.jar"))
    if not android.exists() or not (tools / "aapt2.exe").exists():
        raise RuntimeError("Run scripts/bootstrap_android.py first")
    # Remove only this project's known generated preview directory.
    resolved = BUILD.resolve()
    if resolved != (ROOT / "client/build/preview").resolve() or not resolved.is_relative_to(ROOT.resolve()):
        raise RuntimeError("Unsafe build directory")
    if BUILD.exists():
        shutil.rmtree(BUILD)
    for name in ("classes", "generated", "dex"):
        (BUILD / name).mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(alipay_aar) as aar:
        alipay_jar = BUILD / "alipay-classes.jar"
        alipay_jar.write_bytes(aar.read("classes.jar"))
    app = ROOT / "client/android"
    manifest = app / "AndroidManifest.xml"
    android_ns = "{http://schemas.android.com/apk/res/android}"
    manifest_root = ET.parse(manifest).getroot()
    version = manifest_root.get(android_ns + "versionName")
    if not re.fullmatch(r"[0-9A-Za-z.-]+", version or ""):
        raise RuntimeError("Unsafe version name")
    input_files = sorted(app.rglob("*.java")) + sorted((app / "res").rglob("*")) + sorted((ROOT / "client/core/src").rglob("*.java")) + [manifest, zxing, alipay_aar, Path(__file__).resolve()] + list(pdf_dir.iterdir())
    if field_water:
        input_files += sorted(FIELD.rglob("*.java"))
    input_hashes = {str(p.relative_to(ROOT)).replace("\\", "/"): hashlib.sha256(p.read_bytes()).hexdigest()
                    for p in input_files if p.is_file()}
    if device_tests:
        ns = "{http://schemas.android.com/apk/res/android}"
        tree = ET.parse(manifest)
        root = tree.getroot()
        root.set("package", "io.qzxy.lite.accounttests")
        for permission in list(root.findall("uses-permission")):
            if permission.get(ns + "name") == "android.permission.INTERNET":
                root.remove(permission)
        application = root.find("application")
        for activity in list(application):
            if activity.tag == "activity":
                application.remove(activity)
        ET.SubElement(application, "activity", {ns + "name": "io.qzxy.lite.preview.QzxyAlipayActivity", ns + "exported": "false"})
        ET.SubElement(application, "activity", {ns + "name": "io.qzxy.lite.preview.TimetableActivity", ns + "exported": "false", ns + "configChanges": "orientation|screenSize"})
        ET.SubElement(root, "instrumentation", {ns + "name": "io.qzxy.lite.preview.AccountDeviceTests",
            ns + "targetPackage": "io.qzxy.lite.accounttests"})
        manifest = BUILD / "test-manifest.xml"
        tree.write(manifest, encoding="utf-8", xml_declaration=True)
    if field_water:
        # A separate package name would hide the overlap with the read-only build; instead the version
        # and the launcher label are unmistakable, and the water screen is a separate activity.
        tree = ET.parse(manifest)
        root = tree.getroot()
        root.set(android_ns + "versionCode", str(int(manifest_root.get(android_ns + "versionCode")) + 1))
        root.set(android_ns + "versionName", FIELD_VERSION_NAME)
        version = FIELD_VERSION_NAME
        application = root.find("application")
        application.set(android_ns + "label", FIELD_LABEL)
        ET.SubElement(application, "activity", {android_ns + "name": "io.qzxy.lite.preview.WaterActivity",
            android_ns + "exported": "false", android_ns + "configChanges": "orientation|screenSize"})
        ET.SubElement(application, "activity", {android_ns + "name": "io.qzxy.lite.preview.LifeWaterActivity", android_ns + "exported": "false"})
        manifest = BUILD / "field-manifest.xml"
        tree.write(manifest, encoding="utf-8", xml_declaration=True)
        manifest_root = root
    write_build_flags(field_water, device_tests)
    run([tools / "aapt2.exe", "compile", "--dir", app / "res", "-o", BUILD / "resources.zip"])
    run([tools / "aapt2.exe", "link", "-I", android, "--manifest", manifest,
         "--java", BUILD / "generated", "--custom-package", "io.qzxy.lite.preview",
         "--extra-packages", "com.alipay.sdk",
         "-o", BUILD / "resources.apk", BUILD / "resources.zip"])
    sources = sorted((app / "src").rglob("*.java")) + sorted((ROOT / "client/core/src").rglob("*.java")) + sorted((BUILD / "generated").rglob("*.java"))
    if device_tests:
        sources += sorted((ROOT / "client/androidTest/src").rglob("*.java"))
    if field_water:
        sources += sorted(FIELD.rglob("*.java"))
        if device_tests:
            sources += sorted((ROOT / "client/fieldtestTest/src").rglob("*.java"))
    run([jdk / "bin/javac.exe", "-J-Duser.language=en", "--release", "8", "-Xlint:-options", "-encoding", "UTF-8", "-classpath", os.pathsep.join(str(p) for p in [android, zxing, alipay_jar] + pdf_jars),
         "-d", BUILD / "classes"] + sources)
    classes = BUILD / "classes.jar"
    with zipfile.ZipFile(classes, "w", zipfile.ZIP_DEFLATED) as jar:
        for path in (BUILD / "classes").rglob("*.class"):
            jar.write(path, path.relative_to(BUILD / "classes").as_posix())
    run([jdk / "bin/java.exe", "-cp", tools / "lib/d8.jar", "com.android.tools.r8.D8", "--lib", android,
         "--min-api", "24", "--output", BUILD / "dex", classes, zxing, alipay_jar] + pdf_jars)
    route_hits = check_route_boundary(BUILD / "dex", field_water)
    unsigned = BUILD / "unsigned.apk"
    shutil.copyfile(BUILD / "resources.apk", unsigned)
    with zipfile.ZipFile(unsigned, "a", zipfile.ZIP_DEFLATED) as apk:
        with zipfile.ZipFile(pdf_dir / "pdfbox-android-2.0.27.0.aar") as aar:
            for name in aar.namelist():
                if name.startswith("assets/") and not name.endswith("/"):
                    apk.writestr(name, aar.read(name))
        for dex in (BUILD / "dex").glob("*.dex"):
            apk.write(dex, dex.name)
    aligned = BUILD / "aligned.apk"
    run([tools / "zipalign.exe", "-f", "4", unsigned, aligned])
    key = ROOT / "tools/keys/preview.p12"
    key.parent.mkdir(parents=True, exist_ok=True)
    if not key.exists():
        run([jdk / "bin/keytool.exe", "-genkeypair", "-keystore", key, "-storetype", "PKCS12",
             "-storepass", "android", "-keypass", "android", "-alias", "preview", "-keyalg", "RSA",
             "-keysize", "2048", "-validity", "3650", "-dname", "CN=QZXY Local Preview"])
    delivery = ROOT / "delivery"
    delivery.mkdir(exist_ok=True)
    result = BUILD / "account-tests.apk" if device_tests else delivery / ("科信小助手-" + version + ".apk")
    signer = [jdk / "bin/java.exe", "-jar", tools / "lib/apksigner.jar"]
    run(signer + ["sign", "--v4-signing-enabled", "false", "--ks", key, "--ks-key-alias", "preview", "--ks-pass", "pass:android",
                  "--out", result, aligned])
    run(signer + ["verify", "--verbose", result])
    if device_tests:
        print("Device-only test artifact: " + str(result), flush=True)
        return
    with result.open("rb") as source:
        digest = hashlib.file_digest(source, "sha256").hexdigest()
    report = {"artifact": result.name, "sha256": digest, "bytes": result.stat().st_size,
              "package": manifest_root.get("package"), "version": version,
              "version_code": int(manifest_root.get(android_ns + "versionCode")), "min_sdk": 24,
              "target_sdk": 36, "requested_permissions": [p.get(android_ns + "name") for p in manifest_root.findall("uses-permission")],
              "mode": "campus_release" if field_water else "scan_device_profile_and_order_query_readonly",
              "account_login_implemented": True, "device_profile_implemented": True, "order_query_implemented": True,
              "recovery_store_implemented": True, "water_control_implemented": field_water,
              "field_water_build": field_water, "control_route_occurrences_in_dex": route_hits,
              "live_verification": "See analysis/account-balance-integration.md; this build performs no live requests",
              "live_water_supported": False,
              "source_sha256": input_hashes}
    (delivery / ("科信小助手-" + version + ".build.json")).write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2), flush=True)


if __name__ == "__main__":
    main()
